#ifndef OppleCommands_h
#define OppleCommands_h

#include <Arduino.h>

// Payloads captured from the original OPPLE FE6300 remote.
// The captured FIFO images started with 0x13 (= 19), the length byte;
// LT8920Radio::send() prepends it, so only the 19 payload bytes live here.
namespace OppleCommands {

  constexpr uint8_t LIGHT_ON[19] = {0xA3, 0x71, 0x4D, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x13, 0x00, 0x38, 0x00, 0x00, 0x03, 0x37, 0x00, 0x57, 0x01};
  constexpr uint8_t LIGHT_OFF[19] = {0xA3, 0x71, 0x4D, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x13, 0x00, 0x3C, 0x00, 0x00, 0x03, 0x37, 0x00, 0x57, 0x01};

} // namespace OppleCommands

#endif // OppleCommands_h
